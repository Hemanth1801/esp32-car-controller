'use strict';
const assert=require('node:assert/strict');
const {QuestInput}=require('../web/quest-input.js');
function source(hand){return {handedness:hand,profiles:['oculus-touch-v3'],targetRayMode:'tracked-pointer',gamepad:{mapping:'xr-standard',axes:[0,0,0,0],buttons:Array.from({length:6},()=>({value:0}))}}}
const left=source('left'),right=source('right'),input=new QuestInput(),sources=[left,right];
input.visible=true;
assert.throws(()=>input.read(0,{videoFresh:true}),/tracking/);
assert.deepEqual(input.update(sources,0),{arm:false,stop:false,changed:false});
assert.throws(()=>input.read(0),/video/);
assert.equal(input.neutral(0,true),true);
right.gamepad.buttons[0].value=1;left.gamepad.axes[2]=.56;
assert.equal(input.neutral(0,true),false,'Grip cannot hide non-neutral inputs during arm');
assert.deepEqual(input.read(0,{videoFresh:true}),{throttle:0,steering:0},'Grip release forces zero for both motors');
right.gamepad.buttons[1].value=1;
assert.equal(input.read(0,{videoFresh:true}).throttle,1);assert.ok(Math.abs(input.read(0,{videoFresh:true}).steering-.5)<1e-12);
input.limit=.3;input.invert=true;
assert.equal(input.read(0,{videoFresh:true}).throttle,.3);assert.ok(Math.abs(input.read(0,{videoFresh:true}).steering+.5)<1e-12,'Power limit affects drive only');
right.gamepad.buttons[0].value=0;left.gamepad.buttons[0].value=1;
assert.equal(input.read(0,{videoFresh:true}).throttle,-.3);
right.gamepad.buttons[0].value=.4;
assert.throws(()=>input.read(0,{videoFresh:true}),/Both triggers/);
right.gamepad.buttons[0].value=0;left.gamepad.buttons[0].value=0;
right.gamepad.buttons[4].value=1;
assert.equal(input.update(sources,10).arm,true);assert.equal(input.update(sources,20).arm,false);
right.gamepad.buttons[5].value=1;assert.equal(input.update(sources,30).stop,true);
assert.throws(()=>input.read(211,{videoFresh:true}),/tracking/);
assert.throws(()=>input.update([left],40),/Both tracked/);
assert.throws(()=>input.update(sources,40,()=>false),/Both tracked/);
const unknown=source('left');unknown.profiles=['unknown-controller'];assert.throws(()=>input.update([unknown,right],40),/Both tracked/);
assert.equal(input.update([source('left'),right],50).changed,true);
input.clear();assert.throws(()=>input.read(50,{videoFresh:true}),/tracking/);
assert.equal(input.update(sources,60).arm,false,'Held A cannot arm after a source change');
left.gamepad.axes[2]=NaN;
assert.throws(()=>input.read(60,{videoFresh:true}),/Invalid controller axis/);
console.log('Quest controller input tests passed');
