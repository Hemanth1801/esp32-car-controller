'use strict';
const assert=require('node:assert/strict');
const {PhoneInput,loadSettings,settingsKey}=require('../web/phone-input.js');
const phone=new PhoneInput();phone.enabled=true;
assert.match(phone.armIssue(0),/fresh tilt data/);
assert.equal(phone.calibrate(0),false,'No calibration without real data');
assert.equal(phone.gravity({x:null,y:0,z:9.81},0,0),false);
assert.equal(phone.gravity({x:0,y:0,z:0},0,0),false,'Free fall is not valid steering');
assert.equal(phone.gravity({x:0,y:0,z:9.81},0,0),true);
assert.match(phone.armIssue(0),/Set centre first/);
assert.equal(phone.calibrate(0),true);
assert.equal(phone.armIssue(0),'');
assert.match(phone.armIssue(0,{connected:false}),/ESP connection/);
assert.match(phone.armIssue(0,{otherController:true}),/Another controller/);
assert.match(phone.armIssue(0,{active:false}),/Return to this phone page/);
phone.press(1,1);assert.equal(phone.sample(1).throttle,1);
assert.match(phone.armIssue(1),/Release both drive buttons/);
phone.release(1);assert.deepEqual(phone.sample(1),{throttle:0,steering:0},'Lifting finger zeros both outputs');
phone.press(2,-1);assert.equal(phone.sample(1).throttle,-1);
assert.equal(phone.press(3,1),false,'Opposing fingers cancel; cannot roll into reverse');
assert.deepEqual(phone.sample(1),{throttle:0,steering:0});
for(let i=0;i<60;i++)phone.gravity({x:-4.905,y:0,z:9.81*Math.cos(Math.PI/6)},0,10+i);
assert.ok(Math.abs(phone.steering()-1)<.001,'Portrait right tilt');
assert.match(phone.armIssue(70),/saved centre/);
phone.limit=.2;phone.press(10,1);
assert.equal(phone.sample(70).throttle,.2);assert.ok(phone.sample(70).steering>.99,'Reduced drive power preserves full steering');
phone.release(10);phone.press(11,-1);
assert.equal(phone.sample(70).throttle,-.2);assert.ok(phone.sample(70).steering>.99,'Reverse limit also leaves steering unchanged');
phone.clear();phone.limit=1;
phone.invert=true;assert.ok(phone.steering()<-.99);phone.invert=false;
assert.throws(()=>phone.sample(500),/Tilt data unavailable/,'Sensor loss must not reuse old steering');
phone.rotate();assert.equal(phone.calibrated,false);
phone.gravity({x:0,y:0,z:9.81},90,100);phone.calibrate(100);
for(let i=0;i<60;i++)phone.gravity({x:0,y:-4.905,z:9.81*Math.cos(Math.PI/6)},90,110+i);
assert.ok(phone.steering()>.99,'Landscape right tilt');
phone.gravity({x:0,y:0,z:9.81},270,180);
assert.equal(phone.calibrated,false,'Changing orientation requires centre again');
phone.calibrate(180);
for(let i=0;i<60;i++)phone.gravity({x:0,y:4.905,z:9.81*Math.cos(Math.PI/6)},270,190+i);
assert.ok(phone.steering()>.99,'Opposite landscape right tilt');
const fallback=new PhoneInput();fallback.enabled=true;fallback.orientation(0,0,0,0);fallback.calibrate(0);
for(let i=0;i<60;i++)fallback.orientation(0,30,0,i+1);
assert.ok(fallback.steering()>.99,'Orientation fallback shares gravity-based steering');
const stored=new Map([['espPhoneSettingsV1',JSON.stringify({limit:.3,invert:true})]]);
const storage={getItem:key=>stored.get(key)||null,setItem:(key,value)=>stored.set(key,value)};
assert.deepEqual(loadSettings(storage),{limit:1,invert:true},'Upgrade resets the old limit while preserving inversion');
storage.setItem(settingsKey,JSON.stringify({limit:.6,invert:true}));
assert.equal(loadSettings(storage).limit,.6,'A later user-selected lower speed is preserved');
console.log('Phone input passed: portrait/landscape tilt, calibration, invert, release, multi-touch, stale sensors, rotation and orientation fallback.');
